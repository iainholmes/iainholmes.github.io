assert.throws(()=>assignPlateNumbers(es,{photos:[{id:'a',plate_no:1},{id:'b',plate_no:1}]}),/duplicate/);
assert.ok(plateNumberProblems(es,records).length);
assert.deepEqual(plateNumberProblems(es,numbered),[]);
assert.ok(plateNumberProblems(es,{photos:[...numbered.photos,{id:'unused',plate_no:3,caption:plateCaption(3)}]}).length);
const prompt=reservePrompt({brief:'Synthetic neutral composition for guidance assertions.'});
assert.ok(prompt.includes('slimmer, sleeker, gradually tapered'));
assert.ok(prompt.includes("October 13, 2026 approved illustration"));
assert.ok(prompt.includes("Keep Bosch's distinct stockier English Labrador proportions"));
const legacy=illustrationPrompt({flagship:{title:'Destination must not enter the illustration brief'}},'flagship');
assert.ok(!legacy.includes('Destination must not enter'));
assert.ok(legacy.includes('Portrait 4:5'));
