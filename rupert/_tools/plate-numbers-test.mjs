import assert from 'node:assert/strict';
import {assignPlateNumbers,plateCaption,plateNumberProblems} from './plate-numbers.mjs';
import {credit} from '../assets/js/core/render.js';
import {reservePrompt} from './art-direction.mjs';
import {illustrationPrompt} from '../assets/js/core/adventure.js';
const ed=(id,image,at,status='published')=>({id,status,published_at:at,flagship:{photo:{id:image}}});
const es=[ed('later','b','2026-10-02T07:00:00-04:00'),ed('first','a','2026-10-01T07:00:00-04:00','withdrawn'),ed('same-image','a','2026-10-03T07:00:00-04:00')];
const records={photos:[{id:'b',kind:'plate',provenance:'editorial',caption:'Destination caption'},{id:'a',kind:'print',provenance:'archive',taken_at:'2023-01'}]};
const numbered=assignPlateNumbers(es,records);
assert.equal(numbered.photos.find(p=>p.id==='a').plate_no,1);
assert.equal(numbered.photos.find(p=>p.id==='b').plate_no,2);
assert.deepEqual(assignPlateNumbers(es,numbered),numbered);
assert.equal(plateCaption(1),'TRA Plate No. 001');
assert.equal(plateCaption(23),'TRA Plate No. 023');
assert.ok(!credit({id:'a'},numbered).includes('Archive photograph'));
assert.equal(credit({id:'a'},numbered),'<figcaption class="credit">TRA Plate No. 001</figcaption>');
assert.equal(credit({id:'b'},numbered),'<figcaption class="credit">TRA Plate No. 002</figcaption>');
assert.ok(!credit({id:'b'},numbered).includes('XXX'));
const continuation=assignPlateNumbers([...es,ed('new','c','2026-10-04T07:00:00-04:00')],{photos:[...numbered.photos,{id:'c'}]});
assert.equal(continuation.photos.at(-1).plate_no,3);
const corrected=structuredClone(numbered);corrected.photos[0].alt='Documented correction metadata; same illustration identity';
